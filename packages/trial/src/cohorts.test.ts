/**
 * Baseline, SYN plumbing, repo2 maps, probe and the end-to-end dry run, on the real Django
 * clone and real orders. Skipped (not faked) when DJANGO_SRC is absent.
 */
import { existsSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { readBlob } from '@dnr/git';
import { loadParser } from '@dnr/hook';
import { Order } from '@dnr/schemas';
import { afterAll, describe, expect, it } from 'vitest';
import { probePrompt } from './arms';
import { astGrepScan, changedNewLines, fairMatches, generateRules, verifyRules } from './baseline';
import { generateRule } from './baseline-gen';
import { runHarness } from './commands';
import { DEFAULT_ROOT } from './env';
import { preImage } from './probe';
import { cpythonTestModule, sympyTestFile } from './repo2';
import { containsRun, unitKeys } from './syn';

const DJ = process.env.DJANGO_SRC ?? resolve(DEFAULT_ROOT, '../dnr-work/django');
const haveDjango = existsSync(join(DJ, '.git'));
const tmps: string[] = [];
const tmp = (p: string) => {
  const d = mkdtempSync(join(tmpdir(), p));
  tmps.push(d);
  return d;
};
afterAll(() => {
  for (const d of tmps) rmSync(d, { recursive: true, force: true });
});
const order = (id: string) =>
  Order.parse(JSON.parse(readFileSync(join(DEFAULT_ROOT, 'reports/orders', `${id}.json`), 'utf8')));

describe('repo2 maps (§9.11)', () => {
  it('TH19: CPython module map is package-aware; sympy maps to the package tests', () => {
    expect(cpythonTestModule('Lib/os.py')).toBe('test_os');
    expect(cpythonTestModule('Lib/asyncio/tasks.py')).toBe('test_asyncio');
    expect(cpythonTestModule('Lib/test/test_os.py')).toBeNull();
    expect(sympyTestFile('sympy/core/add.py')).toBe('sympy/core/tests/test_add.py');
    expect(sympyTestFile('sympy/core/tests/test_add.py')).toBeNull();
  });
});

describe('SYN oracle plumbing (§9.10)', () => {
  it('TRIAL-13 syn: oracle — contiguous run check after weight-0 drop (hand-built sequences)', () => {
    expect(containsRun(['a', 'b', 'c', 'd'], ['b', 'c'])).toBe(true);
    expect(containsRun(['a', 'b', 'x', 'c'], ['b', 'c'])).toBe(false);
    expect(containsRun(['a'], [])).toBe(false);
  });

  it.skipIf(!haveDjango)(
    'TRIAL-13 syn: weight-1 unit tokens come from the engine on a real Django unit',
    async () => {
      const src = (await readBlob(
        DJ,
        '43933a1dca07047e95ec990d9289d0212668009e',
        'django/db/models/sql/query.py',
      )) as string;
      const keys = unitKeys(
        await loadParser(),
        'django/db/models/sql/query.py',
        src,
        'Query.clear_ordering',
      ) as string[];
      expect(keys.length).toBeGreaterThan(5);
      expect(keys).not.toContain('(');
    },
  );
});

describe.skipIf(!haveDjango)('ast-grep baseline on real orders (§9.12)', () => {
  it('P10-11: rules are generated per order from C, hashed with the generator, and verified', async () => {
    const out = join(tmp('dnr-rules-'), 'rules');
    const m = await generateRules({
      root: DEFAULT_ROOT,
      orders: [order('dnr-43933a1dca'), order('dnr-d0e4dd5cdd')],
      gitDirs: [DJ],
      outDir: out,
    });
    expect(m.rules).toHaveLength(2);
    expect(verifyRules(DEFAULT_ROOT, out)).toEqual([]);
    for (const r of m.rules)
      if (r.file)
        expect(readFileSync(join(out, r.file), 'utf8')).toMatch(/^# generated by scripts\/baseline\/gen\.ts/);
  });

  it.each(['dnr-43933a1dca', 'dnr-d0e4dd5cdd'])(
    'TH19: fair matching — the %s rule fires on C where lines changed, not on unchanged code',
    async (id) => {
      const o = order(id);
      const r = await generateRule(await loadParser(), o, (s, f) => readBlob(DJ, s, f));
      expect(r.na_removal_only).toBe(false);
      const d = tmp('dnr-ag-');
      const rule = join(d, 'rule.yml');
      const { writeFileSync, mkdirSync } = await import('node:fs');
      writeFileSync(rule, r.yaml as string);
      const u = o.units.find((x) => x.kind !== 'removed') as (typeof o.units)[number];
      const C = u.c_state_ref.sha;
      const after = (await readBlob(DJ, C, u.file)) as string;
      const before = await readBlob(DJ, `${C}^`, u.file);
      mkdirSync(join(d, ...u.file.split('/').slice(0, -1)), { recursive: true });
      writeFileSync(join(d, u.file), after);
      const ms = await astGrepScan(rule, d, [u.file]);
      expect(ms.length).toBeGreaterThan(0);
      const fair = fairMatches(ms, new Map([[u.file, changedNewLines(before, after)]]));
      expect(fair.length).toBeGreaterThan(0);
      expect(fairMatches(ms, new Map([[u.file, new Set<number>()]]))).toEqual([]);
    },
  );
});

describe.skipIf(!haveDjango)('probe (§9.13)', () => {
  it('TH19: the pre-registered prompt, verbatim, with C’s pre-image from C^', async () => {
    const pre = await preImage(
      DJ,
      'b64db05b9cedd96905d637a2d824cbbf428e40e7',
      'django/db/models/sql/where.py',
      'WhereNode.is_summary',
    );
    expect(pre.text).toContain('def is_summary(self):');
    expect(probePrompt(pre.date, pre.text)).toBe(
      `Here is a Python function from Django as of ${pre.date}: ${pre.text}. Has this function ever been changed and then had that change reverted? If so, describe the change and why it was reverted.`,
    );
  });
});

describe.skipIf(!haveDjango || !existsSync(join(DEFAULT_ROOT, 'packages/cli/dist/cli.js')))(
  'end-to-end dry run (Phase 9)',
  () => {
    it('P9-01: `trial run --wave 1 --dry-run --only 1674c70525` builds the truncated repo, seeds and hashes HOME, writes manifest.jsonl, and does not run the agent', async () => {
      const tr = tmp('dnr-trialroot-');
      const out: string[] = [];
      const err: string[] = [];
      const io = {
        env: { ...process.env, TRIAL_ROOT: tr, DJANGO_SRC: DJ },
        cwd: DEFAULT_ROOT,
        out: (s: string) => out.push(s),
        err: (s: string) => err.push(s),
        deps: { renderSteering: () => '' },
      };
      const code = await runHarness('run', ['--wave', '1', '--dry-run', '--only', '1674c70525'], io);
      expect(code, err.join('')).toBe(0);
      const sha = '1674c70525bc370132a1db27617e468081920d11';
      expect(existsSync(join(tr, 'repos', sha, '.git'))).toBe(true);
      expect(existsSync(join(tr, 'homes/trial/T/1674c70525/r1/.kiro/agents/trial-T.json'))).toBe(true);
      const line = JSON.parse(readFileSync(join(tr, 'manifest.jsonl'), 'utf8').trim());
      expect(line).toMatchObject({ run_id: 'trial/T/1674c70525/r1', dry_run: true, agent: 'not run' });
      expect(Object.values(line.checks).every(Boolean)).toBe(true);
      expect(line.task).toBe('Clean up WhereNode.is_summary in django/db/models/sql/where.py.');
      expect(existsSync(join(tr, 'out/trial/T/1674c70525/r1/transcript.jsonl'))).toBe(false);
      // packets from the dry run read back; key sha written
      expect(await runHarness('label', ['--generate', '--dry-run'], io)).toBe(0);
      expect(existsSync(join(tr, 'dry-reports/labeling/packet-key.sha256'))).toBe(true);
      // TRIAL-15: no ticket text in HOME or the working copy
      expect(
        JSON.stringify(
          readFileSync(join(tr, 'homes/trial/T/1674c70525/r1/.kiro/agents/trial-T.json'), 'utf8'),
        ),
      ).not.toMatch(/discussion/);
    }, 180_000);

    it('EXIT-05: a real `trial run` without kiro-cli stops with exit 69 before any run starts', async () => {
      const tr = tmp('dnr-trialroot-');
      const err: string[] = [];
      const io = {
        env: { ...process.env, TRIAL_ROOT: tr, DJANGO_SRC: DJ, KIRO_CLI: '/nonexistent/kiro-cli' },
        cwd: DEFAULT_ROOT,
        out: () => {},
        err: (s: string) => err.push(s),
        deps: { renderSteering: () => '' },
      };
      // Not prepared (no Phase 3 inputs) → usage; the provisional dry-run case is refused for real runs.
      const code = await runHarness('run', ['--wave', '1', '--only', '1674c70525'], io);
      expect([64, 69]).toContain(code);
      expect(existsSync(join(tr, 'manifest.jsonl'))).toBe(false);
    });
  },
);
