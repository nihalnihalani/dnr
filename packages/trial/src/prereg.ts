function files(root: string, rel: string): string[] {
  const p = join(root, rel);
  if (!existsSync(p)) return [];
  if (statSync(p).isFile()) return [rel];
  const out: string[] = [];
  const walk = (d: string) => {
    for (const n of readdirSync(d).sort()) {
      const q = join(d, n);
      if (statSync(q).isDirectory()) walk(q);
      else out.push(relative(root, q));
    }
  };
  walk(p);
  return out;
}

export function hashTable(root: string): {
  rows: Array<{ path: string; sha256: string }>;
  missing: string[];
} {
  const rows: Array<{ path: string; sha256: string }> = [];
  const missing: string[] = [];
  for (const rel of PREREG_INPUTS) {
    const fs = files(root, rel);
    if (fs.length === 0) missing.push(rel);
    for (const f of fs) rows.push({ path: f, sha256: sha256Hex(readFileSync(join(root, f))) });
  }
  return { rows, missing };
}

