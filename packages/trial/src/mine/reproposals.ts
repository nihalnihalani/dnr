/**
 * §9.9 draft counts of documented human re-proposals. Every number in the report comes from a
 * command or request listed next to it.
 */
import { git } from '@dnr/git';
import type { Candidate } from '@dnr/schemas';
import { type GhApi, type PoliteFetcher, parseCsv } from './tickets';

export interface CountRow {
  what: string;
  count: number | null;
  source: string;
  note?: string;
}

export const RELAND_GREP = '(^|[^a-z])(re-?appl(y|ied|ies)|re-?land(s|ed)?)([^a-z]|$)';

export async function countDjangoRelands(
  gitDir: string,
  ref: string,
): Promise<{ rows: CountRow[]; shas: string[] }> {
  const args = ['log', ref, '--no-merges', '-i', '-E', `--grep=${RELAND_GREP}`, '--format=%H%x1f%s'];
  const out = await git(args, { cwd: gitDir });
  const lines = out.split('\n').filter(Boolean);
  const subjectHits = lines.filter((l) => new RegExp(RELAND_GREP, 'i').test(l.split('\x1f')[1] ?? ''));
  return {
    rows: [
      {
        what: 'Django commits whose message mentions reapply/reland',
        count: lines.length,
        source: `git log ${ref.slice(0, 10)} --no-merges -i -E --grep='${RELAND_GREP}'`,
      },
      {
        what: '…of which the subject itself says reapply/reland',
        count: subjectHits.length,
        source: 'same, subject filter',
      },
    ],
    shas: subjectHits.map((l) => l.split('\x1f')[0] as string),
  };
}

export function countRevertOfRevert(cands: readonly Candidate[]): CountRow {
  return {
    what: 'Django reverts tagged revert_of_revert (a revert that re-lands an earlier reverted change)',
    count: cands.filter((c) => c.tags.includes('revert_of_revert')).length,
    source: 'fixtures/candidates.jsonl (tags)',
  };
}

async function ghTotal(gh: GhApi, kind: 'commits' | 'issues', q: string): Promise<number | null> {
  const r = (await gh(`search/${kind}?per_page=1&q=${encodeURIComponent(q)}`)) as { total_count?: number };
  return typeof r.total_count === 'number' ? r.total_count : null;
}

export async function countGithub(gh: GhApi, sleep: (ms: number) => Promise<void>): Promise<CountRow[]> {
  const queries: Array<{ kind: 'commits' | 'issues'; q: string; what: string }> = [
    { kind: 'commits', q: 'repo:python/cpython Reapply', what: 'CPython commits matching "Reapply"' },
    { kind: 'commits', q: 'repo:python/cpython Reland', what: 'CPython commits matching "Reland"' },
    {
      kind: 'issues',
      q: 'repo:django/django is:pr is:closed "was reverted"',
      what: 'Django closed PRs mentioning "was reverted"',
    },
    {
      kind: 'issues',
      q: 'repo:django/django is:pr is:closed "reverted in"',
      what: 'Django closed PRs mentioning "reverted in"',
    },
  ];
  const rows: CountRow[] = [];
  for (const x of queries) {
    await sleep(2000);
    rows.push({
      what: x.what,
      count: await ghTotal(gh, x.kind, x.q),
      source: `gh api search/${x.kind} q='${x.q}' (total_count)`,
      note: 'GitHub search is a text match; each hit still needs a person to confirm it is a re-proposal',
    });
  }
  return rows;
}

export const TRAC_DUP_QUERY =
  'https://code.djangoproject.com/query?status=closed&resolution=duplicate&description=~revert&format=csv&max=10000&col=id&col=summary';

export async function countTracDuplicates(f: PoliteFetcher): Promise<CountRow> {
  const r = await f.get(TRAC_DUP_QUERY);
  const rows =
    r.status === 200 ? parseCsv(r.text).filter((row) => row.length > 1 && /^\d+$/.test(row[0] ?? '')) : null;
  return {
    what: 'Django Trac tickets closed as duplicate whose description mentions "revert"',
    count: rows ? rows.length : null,
    source: TRAC_DUP_QUERY,
    note: rows
      ? 'proxy for "duplicates of reverted tickets"; not yet confirmed by a person'
      : `HTTP ${r.status}`,
  };
}

export function renderReproposals(rows: readonly CountRow[], refSha: string): string {
  const L = [
    '# Human re-proposals (draft)',
    '',
    '§9.9 evidence from human history. **Draft:** these are raw text-match counts. Each hit still needs a person to confirm it is a documented re-proposal of a reverted change before the number is cited.',
    '',
    `Django ref: \`${refSha}\`. Generated by \`pnpm tsx packages/trial/src/mine/cli.ts reproposals\`.`,
    '',
    '| What | Count | Source | Note |',
    '|---|---|---|---|',
    ...rows.map(
      (r) => `| ${r.what} | ${r.count ?? 'n/a'} | \`${r.source.replace(/\|/g, '\\|')}\` | ${r.note ?? ''} |`,
    ),
    '',
  ];
  return L.join('\n');
}
