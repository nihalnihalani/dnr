import type { Candidate } from '@dnr/schemas';
import { RULE_IDS, SKIP_CODES } from './eligibility';
import type { MineResult } from './mine';
import { type MiningWindow, WINDOWS } from './windows';

/** §9.1 step 8 target and the §9.8 floor. */
export const TARGET_K = 30;
export const MIN_K = 8;
const TUNE = 2;

const sha10 = (s: string | null) => (s ? s.slice(0, 10) : '—');
const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

function count<T>(xs: readonly T[], key: (x: T) => string): Map<string, number> {
  const m = new Map<string, number>();
  for (const x of xs) m.set(key(x), (m.get(key(x)) ?? 0) + 1);
  return new Map([...m.entries()].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1)));
}

const noFail = (c: Candidate) => c.window !== null && RULE_IDS.every((id) => c.rules[id] !== 'fail');
const allPass = (c: Candidate) => c.window !== null && RULE_IDS.every((id) => c.rules[id] === 'pass');

/** K that `trial assign` would produce from an eligible pool (tune ranks excluded, capped at the target). */
export function kFromPool(pool: number): number {
  return Math.max(0, Math.min(TARGET_K, pool - TUNE));
}

export function renderEligibility(
  res: MineResult,
  ctx: { repo: string; gitDir: string; ref: string; labels: string | null },
): string {
  const cs = res.mined.map((m) => m.candidate);
  const L: string[] = [];
  const pending = cs.some((c) => RULE_IDS.some((id) => c.rules[id] === 'pending'));
  L.push(`# Eligibility (${ctx.repo})`);
  L.push('');
  L.push(
    'Generated by `pnpm tsx packages/trial/src/mine/cli.ts mine`. Do not edit by hand; a rerun on the same ref is byte-identical.',
  );
  L.push('');
  L.push(`- Ref: \`${ctx.ref}\` = \`${res.refSha}\``);
  L.push(
    `- Discovery: \`git log ${res.refSha.slice(0, 10)} --no-merges -i --grep=revert\` (§9.1 step 1) plus forward/inverse \`git patch-id --stable\` over every non-merge commit (silent reverts, W4)`,
  );
  L.push(
    `- Unit analyzer: \`${res.analyzerSource}\`${res.analyzerSource === 'fallback-indent' ? ' (indentation-based qualnames; the §5.2 engine qualnames and §5.3 weights are not wired in yet, so E5 is pending)' : ''}`,
  );
  L.push(
    `- Reason labels: ${ctx.labels ? `\`${ctx.labels}\`` : 'none (E6 pending until both labelers finish `dnr trial label --reasons`)'}`,
  );
  L.push(`- Candidates: ${cs.length}`);
  L.push('');
  L.push('## K');
  L.push('');
  if (pending) {
    L.push(
      '**K is not final.** Some rules are still pending (see the rule columns). The “pool” columns count candidates with no failed rule, so they are upper bounds: pending rules can only remove reverts. K is computed from the final pool as min(30, pool − 2 tune).',
    );
  } else {
    L.push(
      'Every rule is decided. K = min(30, eligible pool − 2 tune) before `trial assign` checks min_order_weight for tune/gate.',
    );
  }
  L.push('');
  L.push(
    '| Window | Span | Candidates | Pool (no failed rule) | Eligible (all pass) | Cumulative pool | Cumulative eligible | K bound from cumulative pool |',
  );
  L.push('|---|---|---|---|---|---|---|---|');
  let cumPool = 0;
  let cumElig = 0;
  for (const w of WINDOWS) {
    const inW = cs.filter((c) => c.window === w.id);
    const pool = inW.filter(noFail).length;
    const elig = inW.filter(allPass).length;
    cumPool += pool;
    cumElig += elig;
    L.push(
      `| ${w.id} | ${w.label} | ${inW.length} | ${pool} | ${elig} | ${cumPool} | ${cumElig} | ${kFromPool(cumPool)} |`,
    );
  }
  const outside = cs.filter((c) => c.window === null).length;
  L.push(`| — | outside 2015–2025 | ${outside} | — | — | — | — | — |`);
  L.push('');
  L.push(
    `Target K = ${TARGET_K}; the decision needs K ≥ ${MIN_K} (§9.8 D6). Widening order: W0, then W1, W2, W3, W4.`,
  );
  L.push('');
  L.push('## Rule funnel by window');
  L.push('');
  L.push(
    'Each cell counts candidates in the window whose rules up to and including that column have not failed (pending counts as not failed).',
  );
  L.push('');
  L.push(`| Window | ${RULE_IDS.join(' | ')} |`);
  L.push(`|---|${RULE_IDS.map(() => '---').join('|')}|`);
  for (const w of WINDOWS) {
    const inW = cs.filter((c) => c.window === w.id);
    const cells = RULE_IDS.map(
      (_, i) => inW.filter((c) => RULE_IDS.slice(0, i + 1).every((id) => c.rules[id] !== 'fail')).length,
    );
    L.push(`| ${w.id} | ${cells.join(' | ')} |`);
  }
  L.push('');
  L.push('## Pool by proposed reason (rule engine, not labels)');
  L.push('');
  L.push(
    'The rule engine’s proposal is hidden from labelers. These counts are for planning only; E6 uses the blind labels.',
  );
  L.push('');
  L.push(`| Proposed category | ${WINDOWS.map((w) => w.id).join(' | ')} | All |`);
  L.push(`|---|${WINDOWS.map(() => '---').join('|')}|---|`);
  const poolAll = cs.filter(noFail);
  for (const [cat, n] of count(poolAll, (c) => c.proposed_category)) {
    const per = WINDOWS.map(
      (w) => poolAll.filter((c) => c.window === w.id && c.proposed_category === cat).length,
    );
    L.push(`| ${cat} | ${per.join(' | ')} | ${n} |`);
  }
  L.push('');
  L.push('## Skip reasons (first failing rule)');
  L.push('');
  L.push('| skip_reason | Count | Meaning |');
  L.push('|---|---|---|');
  for (const [k, n] of count(cs, (c) => c.skip_reason ?? 'none (eligible)')) {
    const meaning =
      SKIP_CODES[k] ?? (k.startsWith('pending:') ? 'no rule failed yet; these rules are undecided' : '');
    L.push(`| \`${k}\` | ${n} | ${meaning} |`);
  }
  L.push('');
  L.push('## Revert kinds');
  L.push('');
  L.push('| revert_kind | Count |');
  L.push('|---|---|');
  for (const [k, n] of count(cs, (c) => String(c.revert_kind ?? 'none (no usable C)')))
    L.push(`| ${k} | ${n} |`);
  L.push('');
  L.push('## Every candidate');
  L.push('');
  L.push(`Rule states: P pass, F fail, ? pending, - n/a. Sorted by committer date.`);
  L.push('');
  L.push('| R | Date | Win | Method | C | Kind | Tags | Rules E1–E8 | Proposed | skip_reason | Subject |');
  L.push('|---|---|---|---|---|---|---|---|---|---|---|');
  const sym = { pass: 'P', fail: 'F', pending: '?', 'n/a': '-' } as const;
  for (const c of cs) {
    L.push(
      `| \`${sha10(c.revert_sha)}\` | ${c.committed_at.slice(0, 10)} | ${c.window ?? '—'} | ${c.match_method ?? '—'} | \`${sha10(c.original_sha)}\` | ${c.revert_kind ?? '—'} | ${c.tags.join(',') || '—'} | ${RULE_IDS.map((id) => sym[c.rules[id]]).join('')} | ${c.proposed_category} | ${c.skip_reason ? `\`${c.skip_reason}\`` : 'eligible'} | ${esc(c.subject).slice(0, 120)} |`,
    );
  }
  L.push('');
  return L.join('\n');
}

/** §9.11: repo2 needs at least this many eligible reverts in its source root, else sympy. */
export const REPO2_MIN_ELIGIBLE = 15;

export interface SecondRepoSummary {
  repo: 'cpython' | 'sympy';
  candidatesFile: string;
  candidates: number;
  pool: number;
  eligible: number;
  pending: boolean;
}

/** Counts a repo2 candidates file the same way as the Django K table (pool = no failed rule). */
export function summarizeSecondRepo(
  repo: SecondRepoSummary['repo'],
  candidatesFile: string,
  cs: readonly Candidate[],
): SecondRepoSummary {
  const inWin = cs.filter((c) => c.window !== null);
  return {
    repo,
    candidatesFile,
    candidates: cs.length,
    pool: inWin.filter((c) => RULE_IDS.every((id) => c.rules[id] !== 'fail')).length,
    eligible: inWin.filter((c) => RULE_IDS.every((id) => c.rules[id] === 'pass')).length,
    pending: inWin.some((c) => RULE_IDS.some((id) => c.rules[id] === 'pending')),
  };
}

/** The "Second repo" section of the Django eligibility report (P3-20, §9.11). */
export function renderSecondRepo(s: SecondRepoSummary | null): string {
  const L: string[] = ['## Second repo (§9.11)', ''];
  if (!s) {
    L.push(
      'Not mined yet: run `SECOND_SRC=<cpython clone> pnpm tsx packages/trial/src/mine/cli.ts mine --repo cpython` (excluding `Lib/test/**` through `test_globs`).',
    );
    return `${L.join('\n')}\n`;
  }
  L.push(
    `Mined \`${s.repo}\` into \`${s.candidatesFile}\`: ${s.candidates} candidates, pool ${s.pool} (no failed rule, 2015–2025 windows), ${s.eligible} eligible with every rule passing. Test directories are excluded from E4 (\`Lib/test/**\`, \`sympy/**/tests/**\`). The switch rule: fewer than ${REPO2_MIN_ELIGIBLE} eligible reverts in the source root means sympy.`,
  );
  L.push('');
  const min = REPO2_MIN_ELIGIBLE;
  if (s.pool < min)
    L.push(
      `**Choice: sympy.** Even the pool upper bound (${s.pool}) is below ${min}, so ${s.repo} cannot qualify.`,
    );
  else if (s.pending)
    L.push(
      `**Choice: ${s.repo}, provisional.** The pool upper bound (${s.pool}) is at least ${min}, but E6 waits for the reason labels. If fewer than ${min} stay eligible after labeling, the second repo switches to sympy.`,
    );
  else if (s.eligible >= min)
    L.push(`**Choice: ${s.repo}.** ${s.eligible} eligible reverts (at least ${min}).`);
  else L.push(`**Choice: sympy.** Only ${s.eligible} eligible reverts (below ${min}).`);
  return `${L.join('\n')}\n`;
}

export function windowIds(): MiningWindow[] {
  return WINDOWS.map((w) => w.id);
}
