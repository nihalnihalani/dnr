/**
 * Renders every caption and narration line of the §11 video for the §9.8 row that applied, from
 * reports/video/numbers.json (real `dnr trial report` output only), plus the filmed run's fields
 * from reports/video/choice.json (written by whoever applies the §11 choosing rule to real demo
 * runs). Writes captions.srt, shotlist.md and shotlist.json.
 *
 *   pnpm tsx scripts/video/render.ts [--numbers reports/video/numbers.json] [--choice reports/video/choice.json]
 *                                    [--out-dir reports/video] [--allow-pending]
 *
 * Exits 1 when numbers.json is missing or invalid, and 3 (writing nothing) when a slot has no
 * source yet, unless --allow-pending is given for a draft outside reports/.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { readContext } from './context';
import { loadNumbers, NumbersError, PENDING_RE, type VideoNumbers } from './numbers';
import { buildScript, type ScriptContext, ScriptError, type Shot } from './script';
import { shotListMarkdown, toSrt } from './srt';

/** Fields the filmed-run choice file may supply (never trial numbers). */
const CHOICE_KEYS = ['audience', 'package', 'playground_url', 'case', 'run'] as const;

export function mergeChoice(n: VideoNumbers, choice: Record<string, unknown> | null): VideoNumbers {
  if (!choice) return n;
  const out = { ...n } as Record<string, unknown>;
  for (const k of Object.keys(choice)) {
    if (!(CHOICE_KEYS as readonly string[]).includes(k))
      throw new NumbersError(`choice.json may only set ${CHOICE_KEYS.join(', ')}; it sets ${k}`);
    out[k] = choice[k];
  }
  return out as unknown as VideoNumbers;
}

export interface Rendered {
  shots: Shot[];
  srt: string;
  md: string;
  json: string;
  pending: string[];
}

export function render(n: VideoNumbers, ctx: ScriptContext): Rendered {
  const shots = buildScript(n, ctx);
  const header = `Generated by \`scripts/video/render.ts\` from \`reports/video/numbers.json\`: row ${n.row}${n.via_d6 ? ' (via D6)' : ''}, mode ${n.mode ?? 'null'}, prereg-v1 ${n.prereg_sha}, content hash \`${n.content_hash}\`. Do not edit by hand.`;
  const text = shots.flatMap((s) => [...s.caption, s.narration, s.source]).join('\n');
  return {
    shots,
    srt: toSrt(shots),
    md: shotListMarkdown(shots, header),
    json: `${JSON.stringify({ row: n.row, via_d6: n.via_d6, mode: n.mode, content_hash: n.content_hash, shots }, null, 2)}\n`,
    pending: [...new Set(text.match(PENDING_RE) ?? [])],
  };
}

export function readChoice(path: string): Record<string, unknown> | null {
  return existsSync(path) ? (JSON.parse(readFileSync(path, 'utf8')) as Record<string, unknown>) : null;
}

export function main(argv: string[], root = process.cwd()): number {
  const { values: v } = parseArgs({
    args: argv,
    options: {
      numbers: { type: 'string', default: 'reports/video/numbers.json' },
      choice: { type: 'string', default: 'reports/video/choice.json' },
      'out-dir': { type: 'string', default: 'reports/video' },
      'allow-pending': { type: 'boolean', default: false },
    },
  });
  try {
    const n = mergeChoice(loadNumbers(resolve(root, v.numbers)), readChoice(resolve(root, v.choice)));
    const r = render(n, readContext(root));
    if (r.pending.length && !v['allow-pending']) {
      process.stderr.write(
        `video render: ${r.pending.length} slot(s) have no source yet; nothing written:\n${r.pending.map((p) => `  ${p}`).join('\n')}\n`,
      );
      return 3;
    }
    const out = resolve(root, v['out-dir']);
    mkdirSync(out, { recursive: true });
    writeFileSync(join(out, 'captions.srt'), r.srt);
    writeFileSync(join(out, 'shotlist.md'), r.md);
    writeFileSync(join(out, 'shotlist.json'), r.json);
    process.stdout.write(`video render: wrote captions.srt, shotlist.md, shotlist.json in ${out}\n`);
    return 0;
  } catch (e) {
    if (e instanceof NumbersError || e instanceof ScriptError) {
      process.stderr.write(`video render: ${e.message}\n`);
      return 1;
    }
    throw e;
  }
}

if (import.meta.url === `file://${process.argv[1]}`) process.exit(main(process.argv.slice(2)));
